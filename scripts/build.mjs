// Bundles the browser code and CSS into public/static/build with content
// hashes, copies the encoder wasm files, and writes a manifest the Worker
// imports to reference the hashed URLs.
import { build } from "esbuild";
import { createHash } from "node:crypto";
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { basename, extname } from "node:path";

// Files are replaced in place and stale ones removed afterwards, so the dev
// server never sees the directory empty mid-build.
const outdir = "public/static/build";
mkdirSync(outdir, { recursive: true });

const entries = {
  styles: "src/client/styles.css",
  ui: "src/client/ui.ts",
  feed: "src/client/feed.ts",
  detail: "src/client/detail.ts",
  login: "src/client/login.ts",
  upload: "src/client/upload.ts",
  "encode-worker": "src/client/encode-worker.ts",
};

const result = await build({
  entryPoints: entries,
  outdir,
  bundle: true,
  minify: true,
  format: "esm",
  target: "es2022",
  entryNames: "[name]-[hash]",
  metafile: true,
  // Fonts are served from public/static/fonts as-is.
  external: ["/static/*"],
  logLevel: "warning",
});

const manifest = {};
for (const [file, meta] of Object.entries(result.metafile.outputs)) {
  if (!meta.entryPoint) continue;
  const name = Object.keys(entries).find((k) => entries[k] === meta.entryPoint);
  manifest[name] = "/" + file.replace(/^public\//, "");
}

for (const src of [
  "node_modules/@jsquash/avif/codec/enc/avif_enc.wasm",
  "node_modules/@jsquash/jpeg/codec/enc/mozjpeg_enc.wasm",
]) {
  const hash = createHash("sha256").update(readFileSync(src)).digest("hex").slice(0, 8);
  const name = `${basename(src, ".wasm")}-${hash}.wasm`;
  if (!existsSync(`${outdir}/${name}`)) copyFileSync(src, `${outdir}/${name}`);
  manifest[basename(src, extname(src))] = `/static/build/${name}`;
}

const keep = new Set(Object.values(manifest).map((p) => p.split("/").pop()));
for (const f of readdirSync(outdir)) {
  if (!keep.has(f)) rmSync(`${outdir}/${f}`);
}

// Only touch the manifest when it changes; wrangler dev reloads on writes.
const manifestPath = "src/worker/generated/manifest.ts";
const source = `// Generated by scripts/build.mjs. Do not edit.\nexport const assets = ${JSON.stringify(manifest, null, 2)} as const;\n`;
mkdirSync("src/worker/generated", { recursive: true });
if (!existsSync(manifestPath) || readFileSync(manifestPath, "utf8") !== source) {
  writeFileSync(manifestPath, source);
}
console.log("built", Object.keys(manifest).join(", "));
